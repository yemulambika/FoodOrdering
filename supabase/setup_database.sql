-- ============ PROFILES ============
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  updated_at timestamptz,
  username text,
  full_name text,
  avatar_url text,
  website text,
  "group" text NOT NULL DEFAULT 'user',
  expo_push_token text,
  stripe_customer_id text,
  CONSTRAINT username_length CHECK (char_length(username) >= 3 OR username IS NULL)
);

-- ============ RESTAURANTS ============
CREATE TABLE IF NOT EXISTS public.restaurants (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  name text NOT NULL,
  image text,
  delivery_fee real DEFAULT 0 NOT NULL,
  rating real DEFAULT 4.5 NOT NULL
);

-- ============ PRODUCTS ============
CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  name text NOT NULL,
  image text,
  price real NOT NULL,
  description text,
  restaurant_id bigint REFERENCES public.restaurants(id) ON DELETE SET NULL
);

-- ============ ORDERS ============
CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  status text DEFAULT 'New' NOT NULL,
  total double precision DEFAULT 0 NOT NULL,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE
);

-- ============ ORDER ITEMS ============
CREATE TABLE IF NOT EXISTS public.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  size text DEFAULT 'M' NOT NULL,
  quantity integer DEFAULT 1 NOT NULL,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE
);

-- ============ NEW USER TRIGGER ============
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, avatar_url, "group")
  VALUES (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'avatar_url',
    coalesce(nullif(lower(trim(new.raw_user_meta_data->>'group')), ''), 'user')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

