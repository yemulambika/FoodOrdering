-- Restaurants + link products to restaurants.

CREATE TABLE IF NOT EXISTS public.restaurants (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now() NOT NULL,
  name text NOT NULL,
  image text,
  delivery_fee real DEFAULT 0 NOT NULL,
  rating real DEFAULT 4.5 NOT NULL
);

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS restaurant_id bigint REFERENCES public.restaurants(id) ON DELETE SET NULL;

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS description text;

