-- Attach existing products to the first restaurant when unassigned.
UPDATE public.products
SET restaurant_id = (SELECT id FROM public.restaurants ORDER BY id LIMIT 1)
WHERE restaurant_id IS NULL;

ALTER TABLE public.restaurants ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone authenticated can read restaurants" ON public.restaurants;
DROP POLICY IF EXISTS "Admins manage restaurants" ON public.restaurants;

CREATE POLICY "Anyone authenticated can read restaurants"
  ON public.restaurants
  FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "Admins manage restaurants"
  ON public.restaurants
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND lower(profiles."group") = 'admin'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND lower(profiles."group") = 'admin'
    )
  );
